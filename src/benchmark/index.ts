function uniqueFiles<T extends { path: string }>(values: T[], limit: number): T[] {
  const seen = new Set<string>();
  return values.filter((value) => value.path && !seen.has(value.path) && seen.add(value.path)).slice(0, limit);
}

function metrics(results: string[], gold: Set<string>, testPaths: Set<string>) {
  const hits = results.filter((file) => gold.has(file));
  return {
    recallAtK: Number((hits.length / gold.size).toFixed(3)),
    precisionAtK: Number((hits.length / Math.max(1, results.length)).toFixed(3)),
    fileHitCount: hits.length,
    testHitCount: hits.filter((file) => testPaths.has(file)).length,
  };
}

function safeCommand(command: string, args: string[]): string {
  const executable = process.platform === "win32" && command === "docker" ? (process.env.ComSpec ?? "cmd.exe") : command;
  const finalArgs = process.platform === "win32" && command === "docker" ? ["/d", "/s", "/c", "docker.cmd", ...args] : args;
  try { return execFileSync(executable, finalArgs, { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim(); }
  catch { return "unavailable"; }
}

function markdown(report: BenchmarkReport): string {
  const lines = [
    "# Executed ShopFlow benchmark",
    "",
    "> Generated by `pnpm benchmark`. ShopFlow is a deterministic product demonstration, not a general scientific claim.",
    "",
    `Generated: ${report.environment.generatedAt}`,
    "",
    `Command: \`pnpm benchmark\` · Node: \`${report.environment.node}\` · Platform: \`${report.environment.platform}\``,
    "",
    `Git commit: \`${report.environment.commit}\` · Worktree dirty: \`${String(report.environment.worktreeDirty)}\``,
    "",
    `HydraDB image: \`${report.environment.hydraImage}\``,
    "",
    `Static indexing: ${report.indexing.staticAnalysisMs} ms; HydraDB ingestion: ${report.indexing.ingestionMs} ms; ${report.indexing.nodes} nodes; ${report.indexing.edges} edges.`,
    "",
    "| Case | K | Lexical recall | Graph recall | Lexical precision | Graph precision | Graph evidence |",
    "|---|---:|---:|---:|---:|---:|---:|",
    ...report.cases.map((item) => `| ${item.id} | ${item.k} | ${item.lexical.recallAtK.toFixed(3)} | ${item.graph.recallAtK.toFixed(3)} | ${item.lexical.precisionAtK.toFixed(3)} | ${item.graph.precisionAtK.toFixed(3)} | ${item.graph.evidencePathCount} |`),
    "",
    `Macro average: lexical Recall@K **${report.summary.lexicalRecallAtK.toFixed(3)}**, graph Recall@K **${report.summary.graphRecallAtK.toFixed(3)}**; lexical Precision@K **${report.summary.lexicalPrecisionAtK.toFixed(3)}**, graph Precision@K **${report.summary.graphPrecisionAtK.toFixed(3)}**.`,
    "",
    "The baseline ranks filename, path, symbol-name, qualified-name, quoted phrase, and token overlap only. Graph retrieval starts from the same text signals and then executes bounded HydraDB traversal. Ties and lexical wins are preserved.",
    "",
  ];
  return `${lines.join("\n")}\n`;
}

type CaseMetrics = ReturnType<typeof metrics> & { files: string[]; estimatedContextTokens: number; evidencePathCount: number; latencyMs: number };
interface BenchmarkReport {
  schemaVersion: 1;
  environment: { generatedAt: string; node: string; platform: string; commit: string; worktreeDirty: boolean; hydraImage: string; hydra: ReturnType<typeof publicHydraConfig> };
  indexing: { staticAnalysisMs: number; ingestionMs: number; nodes: number; edges: number };
  cases: Array<{ id: string; task: string; k: number; goldFiles: BenchmarkCaseGold[]; lexical: CaseMetrics; graph: CaseMetrics }>;
  summary: { lexicalRecallAtK: number; graphRecallAtK: number; lexicalPrecisionAtK: number; graphPrecisionAtK: number; cases: number };
}
type BenchmarkCaseGold = { path: string; rationale: string };

const fixture = path.resolve("fixtures", "shopflow");
const config = loadHydraConfig();
const client = new HydraDbClient(config);
if (!(await client.readiness())) throw new Error("HydraDB is unavailable. Run pnpm hydra:up && pnpm hydra:wait before benchmarking.");
const index = await indexRepository(fixture);
const ingestion = await ingestRepository(client, index);
const testPaths = new Set(index.nodes.filter((node) => node.label === "File" && node.properties.isTest === true).map((node) => String(node.properties.path)));
const caseReports: BenchmarkReport["cases"] = [];

for (const benchmarkCase of benchmarkCases) {
  const gold = new Set(benchmarkCase.goldFiles.map((item) => item.path));
  const lexicalStarted = performance.now();
  const lexicalNodes = lexicalSearch(index, benchmarkCase.task, 30);
  const lexicalFiles = uniqueFiles(lexicalNodes.map((result) => ({ path: String(result.node.properties.path) })), benchmarkCase.maximumResults).map((item) => item.path);
  const lexicalLatency = performance.now() - lexicalStarted;
  const seeds = taskSeeds(index, benchmarkCase.task, 3);
  const graphStarted = performance.now();
  const impact = await analyzeImpact(client, index, seeds, benchmarkCase.task, 3, 100);
  const graphFiles = uniqueFiles(impact.recommendations.map((item) => ({ path: item.path })), benchmarkCase.maximumResults).map((item) => item.path);
  const graphLatency = performance.now() - graphStarted;
  const pack = await buildContextPack(index, impact, { task: benchmarkCase.task, budget: 2_000, namespace: config.namespace, graphId: config.graphId });
  const lexicalBase = metrics(lexicalFiles, gold, testPaths);
  const graphBase = metrics(graphFiles, gold, testPaths);
  caseReports.push({
    id: benchmarkCase.id,
    task: benchmarkCase.task,
    k: benchmarkCase.maximumResults,
    goldFiles: benchmarkCase.goldFiles,
    lexical: { ...lexicalBase, files: lexicalFiles, estimatedContextTokens: lexicalNodes.slice(0, benchmarkCase.maximumResults).reduce((sum, result) => sum + Math.ceil(String(result.node.properties.signature ?? result.node.properties.path).length / 4), 0), evidencePathCount: 0, latencyMs: Number(lexicalLatency.toFixed(2)) },
    graph: {
      ...graphBase,
      files: graphFiles,
      estimatedContextTokens: pack.estimatedTokens,
      evidencePathCount: graphFiles.filter((file) => impact.recommendations.some((item) => item.path === file && item.evidence.nodeIds.length > 0)).length,
      latencyMs: Number(graphLatency.toFixed(2)),
    },
  });
}

const average = (selector: (item: BenchmarkReport["cases"][number]) => number) => Number((caseReports.reduce((sum, item) => sum + selector(item), 0) / caseReports.length).toFixed(3));
const report: BenchmarkReport = {
  schemaVersion: 1,
  environment: {
    generatedAt: new Date().toISOString(), node: process.version, platform: `${process.platform}/${process.arch}`,
    commit: safeCommand("git", ["rev-parse", "HEAD"]),
    worktreeDirty: safeCommand("git", ["status", "--porcelain"]).length > 0,
    hydraImage: safeCommand("docker", ["image", "inspect", "ghcr.io/hydra-db/hydradb:latest", "--format={{.Id}}"]),
    hydra: publicHydraConfig(config),
  },
  indexing: {
    staticAnalysisMs: index.diagnostics.elapsedMs,
    ingestionMs: Number(ingestion.batches.reduce((sum, batch) => sum + batch.latencyMs, 0).toFixed(2)),
    nodes: ingestion.nodeCount,
    edges: ingestion.edgeCount,
  },
  cases: caseReports,
  summary: {
    lexicalRecallAtK: average((item) => item.lexical.recallAtK),
    graphRecallAtK: average((item) => item.graph.recallAtK),
    lexicalPrecisionAtK: average((item) => item.lexical.precisionAtK),
    graphPrecisionAtK: average((item) => item.graph.precisionAtK),
    cases: caseReports.length,
  },
};
const generatedDirectory = path.resolve("generated", "benchmark");
await mkdir(generatedDirectory, { recursive: true });
await mkdir(path.resolve("docs"), { recursive: true });
await writeFile(path.join(generatedDirectory, "report.json"), `${JSON.stringify(report, null, 2)}\n`, "utf8");
await writeFile(path.join(generatedDirectory, "report.md"), markdown(report), "utf8");
await writeFile(path.resolve("docs", "BENCHMARK_RESULTS.md"), markdown(report), "utf8");
console.log(markdown(report));
